#!/bin/bash
# Usage: theme.sh [dark|light|toggle|apply]
# apply (default) re-applies whatever mode is currently saved, used at i3 startup.
#
# Each mode has a rotating photo wallpaper (Scripts/photo_wallpaper.sh: dark =
# forests, light = animals) with an accent colour picked from the photo. The
# accent is applied to: polybar "primary", i3 window borders / title bars,
# Alacritty cursor + selection, and the lock screen (which reads the cache itself).
# Without a photo (first run, offline from the start) the bundled
# desktop_bgs image and the stock purple are used.

DOTFILES="$HOME/GitHub/dotfiles"
STATE_FILE="$HOME/.cache/theme_mode"

current=$(cat "$STATE_FILE" 2>/dev/null)
[ -z "$current" ] && current="dark"

case "$1" in
    toggle)     [ "$current" = "dark" ] && mode="light" || mode="dark" ;;
    dark|light) mode="$1" ;;
    *)          mode="$current" ;;
esac

echo "$mode" > "$STATE_FILE"

# --- palette (must match polybar/colors-<mode>.ini) -------------------------
if [ "$mode" = "dark" ]; then
    BUNDLED="$DOTFILES/desktop_bgs/death_bg.png"; TERM_THEME=catppuccin-mocha
    BG="#282A2E"; BG_ALT="#373B41"; FG="#C5C8C6"; DISABLED="#707880"; ALERT="#A54242"
else
    BUNDLED="$DOTFILES/desktop_bgs/light_bg.jpg"; TERM_THEME=bone-light
    BG="#F2EEE6"; BG_ALT="#E4DDD0"; FG="#3A352E"; DISABLED="#A39C8F"; ALERT="#C0392B"
fi
ACCENT=$(awk -F' = ' '/^primary/ {print $2}' "$DOTFILES/polybar/colors-$mode.ini")

# --- wallpaper + accent: current photo -> reserve photo -> bundled ----------
PHOTOS="$HOME/.cache/wallpapers/$mode"
WALL="$BUNDLED"
for s in current previous; do
    if magick identify "$PHOTOS/$s.jpg" >/dev/null 2>&1; then
        WALL="$PHOTOS/$s.jpg"
        A=$(cat "$PHOTOS/$s.accent" 2>/dev/null)
        [[ "$A" =~ ^#[0-9A-Fa-f]{6}$ ]] || A=$("$DOTFILES/Scripts/accent_color.sh" "$WALL" "" "$mode")
        ACCENT=$A
        break
    fi
done

# text drawn on top of the accent (focused title bar): whichever of dark/white
# contrasts more (WCAG relative luminance; the crossover is ~0.18)
ON_ACCENT=$(awk -v h="${ACCENT#\#}" 'function lin(c){ return c <= 0.04045 ? c/12.92 : ((c+0.055)/1.055)^2.4 }
    BEGIN{ r=lin(strtonum("0x" substr(h,1,2))/255); g=lin(strtonum("0x" substr(h,3,2))/255); b=lin(strtonum("0x" substr(h,5,2))/255)
    print (0.2126*r + 0.7152*g + 0.0722*b > 0.18) ? "#1D1F24" : "#FFFFFF" }')

# --- polybar ----------------------------------------------------------------
sed "s/^primary = .*/primary = $ACCENT/" "$DOTFILES/polybar/colors-$mode.ini" \
    > "$DOTFILES/polybar/colors-current.ini"

# --- alacritty (live-reloads the imported file) -----------------------------
awk -v a="$ACCENT" '
    /^\[/ { sec = $0 }
    sec == "[colors.cursor]"    && /^cursor *=/     { $0 = "cursor = \"" a "\"" }
    sec == "[colors.selection]" && /^background *=/ { $0 = "background = \"" a "\"" }
    { print }' "$DOTFILES/alacritty/$TERM_THEME.toml" > "$DOTFILES/alacritty/theme-current.toml.tmp" \
  && mv "$DOTFILES/alacritty/theme-current.toml.tmp" "$DOTFILES/alacritty/theme-current.toml"

# --- i3 window colours (included by i3/config) ------------------------------
I3_COLORS="$DOTFILES/i3/theme-current.conf"
row() { printf '%-23s %-10s %-10s %-10s %-10s %s\n' "$@"; }
NEW=$(
    echo "# Generated by Scripts/theme.sh ($mode) - do not edit"
    row "# class" border backgr. text indicator child_border
    row client.focused          "$ACCENT" "$ACCENT" "$ON_ACCENT" "$ACCENT" "$ACCENT"
    row client.focused_inactive "$BG_ALT" "$BG_ALT" "$FG"        "$BG_ALT" "$BG_ALT"
    row client.unfocused        "$BG"     "$BG"     "$DISABLED"  "$BG"     "$BG"
    row client.urgent           "$ALERT"  "$ALERT"  "#FFFFFF"    "$ALERT"  "$ALERT"
    row client.placeholder      "$BG"     "$BG"     "$FG"        "$BG"     "$BG"
    echo "client.background       $BG"
)
if [ "$NEW" != "$(cat "$I3_COLORS" 2>/dev/null)" ]; then
    printf '%s\n' "$NEW" > "$I3_COLORS"
    i3-msg -q reload >/dev/null 2>&1     # only on change (this script runs from exec_always)
fi

# --- wallpaper + polybar ----------------------------------------------------
"$DOTFILES/Scripts/wallpaper.sh" "$WALL"
killall polybar 2>/dev/null
"$DOTFILES/polybar/launch.sh" &
